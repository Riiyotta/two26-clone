#!/usr/bin/env python3
"""Derive schema/pagespec.schema.json (Draft-07) from the section contracts, asset roles,
motion patterns and templates. verify_all.py rebuilds it in memory and fails if the file on
disk drifted from the contracts.

    python3 extraction/build_schema.py          # rewrite schema/pagespec.schema.json
    python3 extraction/build_schema.py --check  # exit 1 if the file is stale
Standard library only.
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PAGESPEC_VERSION = "1.0.0"
URL_PATTERN = "^(/|#|https?://|mailto:)"
EMAIL_PATTERN = "^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$"
TOKEN_PATTERN = "^[a-z][a-z0-9.-]*$"


def _j(rel):
    return json.loads((REPO / rel).read_text())


def field_schema(f):
    t = f["type"]
    if t == "text":
        return {"type": "string", "minLength": 1}
    if t == "url":
        return {"type": "string", "pattern": URL_PATTERN}
    if t == "email":
        return {"type": "string", "pattern": EMAIL_PATTERN}
    if t == "text-list":
        return {"type": "array", "items": {"type": "string", "minLength": 1}, "minItems": f.get("minItems", 0), "maxItems": f["maxItems"]}
    if t == "items":
        return {"type": "array", "minItems": f.get("minItems", 0), "maxItems": f["maxItems"], "items": object_schema(f["fields"])}
    raise ValueError("unknown field type " + t)


def object_schema(fields):
    return {"type": "object", "additionalProperties": False,
            "required": sorted(k for k, v in fields.items() if v.get("required", True)),
            "properties": {k: field_schema(v) for k, v in fields.items()}}


def build(repo=REPO):
    global REPO
    REPO = Path(repo)
    sections = {p.stem: json.loads(p.read_text()) for p in sorted((REPO / "sections").glob("*.json"))}
    roles = sorted(_j("assets/asset-roles.json")["roles"])
    mp = _j("tokens/00-foundation/motion-patterns.json")
    templates = sorted(_j("templates/templates.json")["templates"])
    policy = _j("tokens/llm/token-policy.json")
    branches = []
    for sid, c in sections.items():
        branches.append({"if": {"properties": {"section": {"const": sid}}, "required": ["section"]},
                         "then": {"properties": {"variant": {"enum": c["variants"]},
                                                 "content": object_schema(c["content"]["fields"])}}})
    node = {"type": "object", "additionalProperties": False,
            "required": ["section", "variant", "retrievalEligible", "content", "motion"],
            "properties": {
                "section": {"enum": sorted(sections)},
                "variant": {"type": "string"},
                "retrievalEligible": {"type": "boolean"},
                "content": {"type": "object"},
                "assets": {"type": "array", "items": {"$ref": "#/definitions/asset"}},
                "tokens": {"$ref": "#/definitions/tokens"},
                "motion": {"$ref": "#/definitions/motion"}},
            "allOf": branches}
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "pagespec.schema.json",
        "title": "two26 design-repo PageSpec",
        "description": "Generated by extraction/build_schema.py from sections/*.json. Do not hand-edit.",
        "type": "object", "additionalProperties": False,
        "required": ["pageSpecVersion", "mode", "template", "route", "theme", "site", "meta", "nodes"],
        "properties": {
            "pageSpecVersion": {"const": PAGESPEC_VERSION},
            "mode": {"enum": ["reference", "generated"]},
            "template": {"enum": templates},
            "route": {"type": "string", "pattern": "^/"},
            "theme": {"enum": policy["themes"]},
            "site": {"type": "object", "additionalProperties": False, "required": ["brandName", "baseUrl"],
                     "properties": {"brandName": {"type": "string", "minLength": 1}, "baseUrl": {"type": "string", "pattern": "^https?://"}}},
            "meta": {"type": "object", "additionalProperties": False, "required": ["title", "description"],
                     "properties": {"title": {"type": "string", "minLength": 1}, "description": {"type": "string", "minLength": 1}}},
            "nodes": {"type": "array", "minItems": 1, "items": {"$ref": "#/definitions/node"}}},
        "definitions": {
            "node": node,
            "asset": {"type": "object", "additionalProperties": False, "required": ["slot", "assetRole"],
                      "properties": {"slot": {"type": "string"}, "assetRole": {"enum": roles}, "src": {"type": "string"},
                                     "alt": {"type": "string"}, "brief": {"type": "string"}}},
            "tokens": {"type": "object", "additionalProperties": False,
                       "properties": {k: {"type": "string", "pattern": TOKEN_PATTERN} for k in sorted(policy["slots"])}},
            "motion": {"type": "object", "additionalProperties": False, "required": ["pattern", "trigger", "reducedMotionFallback"],
                       "properties": {"pattern": {"enum": sorted(mp["patterns"])}, "trigger": {"enum": mp["triggers"]},
                                      "reducedMotionFallback": {"enum": mp["fallbacks"]}}}}}


def dumps(s):
    return json.dumps(s, indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    target = REPO / "schema/pagespec.schema.json"
    fresh = dumps(build())
    if "--check" in sys.argv:
        ok = target.exists() and target.read_text() == fresh
        print("schema up to date" if ok else "schema/pagespec.schema.json is STALE vs sections/*.json")
        sys.exit(0 if ok else 1)
    target.write_text(fresh)
    print("wrote", target.relative_to(REPO))
